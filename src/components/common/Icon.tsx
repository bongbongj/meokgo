export type IconName = keyof typeof ICONS;

interface IconProps {
  name: IconName;
  size: number;
  color: string;
}

export default function Icon({ name, size, color }: IconProps) {
  const { viewBox, paths }: IconDef = ICONS[name];
  const [vbW, vbH] = typeof viewBox === "number" ? [viewBox, viewBox] : viewBox;
  return (
    <Svg width={(size * vbW) / vbH} height={size} viewBox={`0 0 ${vbW} ${vbH}`} fill="none">
      {paths.map((p) =>
        p.strokeWidth ? (
          <Path
            key={p.d}
            d={p.d}
            stroke={p.fixedColor ?? color}
            strokeWidth={p.strokeWidth}
            strokeLinecap={p.butt ? "butt" : "round"}
            strokeLinejoin="round"
          />
        ) : (
          <Path key={p.d} d={p.d} fill={p.fixedColor ?? color} />
        ),
      )}
    </Svg>
  );
}
